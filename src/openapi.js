// The `openapi` option: validators for an OpenAPI document's request bodies,
// written beside it as `<name>.validators.mjs` and `.d.mts`. The module is
// plain source, one `new Validator(schema)` per operation from
// ata-validator/openapi's operationSchemas, so a server can import it as it
// is and run it on the runtime, while a page's build compiles each validator
// away like any other (src/compile-away.js): both read the same file, so the
// page and the server check the same schema.
//
//   ata({ openapi: 'openapi.json' })
//   import { createUserBody } from './openapi.validators.mjs'
//   createUserBody.validate(form)
//
// JSON documents are read as they are; YAML needs the `yaml` package.

import fs from 'node:fs/promises'
import path from 'node:path'

// Operation names come from ata-validator/openapi as identifiers already
// (its operationId in camel case, or method and path).
const upper = (s) => s[0].toUpperCase() + s.slice(1)

async function readDocument(file) {
  const text = await fs.readFile(file, 'utf8')
  if (/\.ya?ml$/i.test(file)) {
    let yaml
    try { yaml = await import('yaml') } catch { throw new Error(`unplugin-ata: reading ${file} needs the "yaml" package (npm install yaml), or give the document as JSON`) }
    return (yaml.default ?? yaml).parse(text)
  }
  return JSON.parse(text)
}

function entries(option) {
  const list = Array.isArray(option) ? option : [option]
  return list.filter(Boolean).map((e) => (typeof e === 'string' ? { file: e } : e))
}

// The module and its types for one document.
export function render(bodies, validatorOptions, toTypeScript, source) {
  const names = Object.keys(bodies)
  const opts = validatorOptions && Object.keys(validatorOptions).length ? ', ' + JSON.stringify(validatorOptions) : ''
  let js = `// Generated by @ata-project/unplugin from ${source}. Do not edit.\n// One validator per operation's request body; a page's build compiles each.\nimport { Validator } from 'ata-validator'\n\n`
  let dts = `// Generated by @ata-project/unplugin from ${source}. Do not edit.\nexport interface ValidationError { keyword: string; instancePath: string; schemaPath: string; params: Record<string, unknown>; message: string; [field: string]: unknown }\nexport type Result<T> = { valid: true; data: T; errors: readonly never[] } | { valid: false; errors: ValidationError[] }\n\n`
  const taken = new Set()
  names.forEach((op, i) => {
    const id = op + 'Body'; const ns = upper(op)
    if (taken.has(id) || taken.has(ns)) throw new Error(`unplugin-ata: two operations in ${source} would both be written as ${id}`)
    taken.add(id); taken.add(ns)
    // A literal, which the build can read; JSON.parse where a name __proto__
    // would set the literal's prototype instead of being a property.
    const text = JSON.stringify(bodies[op])
    const lit = text.includes('"__proto__"') ? `JSON.parse(${JSON.stringify(text)})` : text
    js += `const v${i} = new Validator(${lit}${opts})\nexport const ${id} = { validate: (data) => v${i}.validate(data), isValidObject: (data) => v${i}.isValidObject(data) }\n`
    let types = 'export type Body = unknown'
    if (toTypeScript) {
      const t = toTypeScript(bodies[op], { name: 'Body' })
      const a = t.search(/^export (type|interface) /m); const b = t.indexOf('export interface ValidationError')
      if (a !== -1 && b > a) types = t.slice(a, b).trim()
    }
    dts += `export declare namespace ${ns} {\n${types.replace(/^/gm, '  ')}\n}\nexport type ${ns}Body = ${ns}.Body\nexport declare const ${id}: { validate(data: unknown): Result<${ns}Body>; isValidObject(data: unknown): data is ${ns}Body }\n\n`
  })
  return { js, dts }
}

// Write the validators for every document the option names. Returns the
// files written and the operations found.
export async function compileOpenAPI(option, root, write) {
  const { operationSchemas } = await import('ata-validator/openapi')
  let toTypeScript = null
  try { const m = await import('ata-validator'); toTypeScript = (m.default ?? m).toTypeScript } catch {}
  const out = []
  for (const entry of entries(option)) {
    const file = path.resolve(root, entry.file)
    const doc = await readDocument(file)
    const bodies = operationSchemas(doc)
    const base = path.join(path.dirname(file), path.basename(file).replace(/\.(json|ya?ml)$/i, ''))
    const { js, dts } = render(bodies, entry.validatorOptions || null, toTypeScript, path.basename(file))
    const changed = (await write(base + '.validators.mjs', js)) | (await write(base + '.validators.d.mts', dts))
    out.push({ file, module: base + '.validators.mjs', operations: Object.keys(bodies), changed: !!changed })
  }
  return out
}
